#!/usr/bin/env python3
"""Generate idempotent backend initialization SQL for bundled dashboards."""

from __future__ import annotations

import argparse
import json
import uuid
from pathlib import Path
from typing import Any


REPO_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_DASHBOARD_DIRECTORY = REPO_ROOT / "backend" / "static" / "custom-dashboards"
DEFAULT_SQL_DIRECTORY = REPO_ROOT / "backend" / "sqlscripts" / "default_custom_dashboards"
DASHBOARD_UUID_NAMESPACE = uuid.UUID("d6ad42f5-7531-4d4c-a90d-11b29c2ed567")
DIALECTS = ("sqlite", "mysql", "postgres")


def stable_dashboard_id(source_id: str) -> str:
    source_id = source_id.strip()
    if not source_id:
        raise ValueError("dashboard manifest id must not be empty")
    return str(uuid.uuid5(DASHBOARD_UUID_NAMESPACE, source_id))


def sql_literal(value: Any, dialect: str) -> str:
    text = str(value)
    if dialect == "mysql":
        text = text.replace("\\", "\\\\")
    return "'" + text.replace("'", "''") + "'"


def dashboard_insert_sql(source_id: str, dashboard: dict[str, Any], dialect: str) -> str:
    dashboard_id = stable_dashboard_id(source_id)
    config = json.dumps(dashboard, ensure_ascii=False, separators=(",", ":"))
    values = [
        sql_literal(dashboard_id, dialect),
        sql_literal(dashboard.get("name") or source_id, dialect),
        sql_literal(dashboard.get("description") or "", dialect),
        "(SELECT user_id FROM \"user\" WHERE username = 'admin' LIMIT 1)",
        sql_literal(dashboard.get("visibility") or "everyone", dialect),
        sql_literal("[]", dialect),
        sql_literal(config, dialect),
        "CURRENT_TIMESTAMP",
        "CURRENT_TIMESTAMP",
    ]
    return "\n".join(
        [
            f"-- {source_id}: {dashboard.get('name') or source_id}",
            "INSERT INTO custom_dashboard",
            "  (id, name, description, owner_id, visibility, team_ids, config, created_at, updated_at)",
            "SELECT",
            "  " + ",\n  ".join(values),
            "WHERE NOT EXISTS (",
            f"  SELECT 1 FROM custom_dashboard WHERE id = {sql_literal(dashboard_id, dialect)}",
            ");",
        ]
    )


def load_dashboards(directory: Path) -> list[tuple[str, dict[str, Any]]]:
    manifest_path = directory / "manifest.json"
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    entries = manifest.get("dashboards")
    if not isinstance(entries, list) or not entries:
        raise ValueError(f"dashboard manifest contains no dashboards: {manifest_path}")

    dashboards = []
    seen_ids: set[str] = set()
    for entry in entries:
        source_id = str(entry.get("id") or "").strip()
        filename = str(entry.get("file") or "").strip()
        if source_id in seen_ids:
            raise ValueError(f"duplicate dashboard manifest id: {source_id}")
        if not filename or Path(filename).name != filename:
            raise ValueError(f"invalid dashboard filename in manifest: {filename!r}")
        dashboard_path = directory / filename
        dashboard = json.loads(dashboard_path.read_text(encoding="utf-8"))
        dashboards.append((source_id, dashboard))
        seen_ids.add(source_id)
    return dashboards


def generate_sql(directory: Path, output_directory: Path) -> dict[str, Any]:
    dashboards = load_dashboards(directory)
    output_directory.mkdir(parents=True, exist_ok=True)
    outputs = []
    for dialect in DIALECTS:
        header = "\n".join([
            "-- Generated by scripts/generate_default_custom_dashboard_sql.py.",
            "-- Inserts missing built-in dashboards only; existing user-edited rows are preserved.",
        ])
        statements = [dashboard_insert_sql(source_id, dashboard, dialect) for source_id, dashboard in dashboards]
        output_path = output_directory / f"default_custom_dashboards-{dialect}.sql"
        output_path.write_text("\n\n".join([header, *statements]) + "\n", encoding="utf-8")
        outputs.append(str(output_path))
    return {"dashboards": len(dashboards), "outputs": outputs}


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Generate backend initialization SQL for default dashboards.")
    parser.add_argument("--dashboard-dir", type=Path, default=DEFAULT_DASHBOARD_DIRECTORY)
    parser.add_argument("--output-dir", type=Path, default=DEFAULT_SQL_DIRECTORY)
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    result = generate_sql(args.dashboard_dir, args.output_dir)
    print(json.dumps(result, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
