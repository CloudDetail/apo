import test from 'node:test'
import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import { URL } from 'node:url'

const sourceFor = (path) => readFileSync(new URL(path, import.meta.url), 'utf8')

const indexSource = sourceFor('./index.jsx')

test('system health page delegates reusable status and queue UI out of the main component', () => {
  const statusSource = sourceFor('./components/HealthStatus.jsx')
  const pendingQueueSource = sourceFor('./components/PendingIssueQueue.jsx')
  const thresholdSource = sourceFor('./components/ThresholdSettingsContent.jsx')
  const detailLoadingSource = sourceFor('./components/DetailLoading.jsx')
  const overviewSystemTableSource = sourceFor('./components/OverviewSystemTable.jsx')
  const detailHeaderSource = sourceFor('./components/DetailHeader.jsx')
  const serviceHealthTableSource = sourceFor('./components/ServiceHealthTable.jsx')
  const overviewSummarySource = sourceFor('./components/OverviewSummary.jsx')
  const metricVisualTileSource = sourceFor('./components/MetricVisualTile.jsx')
  const systemScoreTrendCellSource = sourceFor('./components/SystemHealthScoreTrendCell.jsx')
  const detailTrendSectionSource = sourceFor('./components/DetailTrendSection.jsx')
  const healthScoreHelpSource = sourceFor('./components/HealthScoreHelp.jsx')
  const overviewInitialLoadingSource = sourceFor('./components/OverviewInitialLoading.jsx')

  assert.ok(indexSource.includes("from './components/HealthStatus.jsx'"))
  assert.ok(indexSource.includes("from './components/PendingIssueQueue.jsx'"))
  assert.ok(indexSource.includes("from './components/ThresholdSettingsContent.jsx'"))
  assert.ok(indexSource.includes("from './components/DetailLoading.jsx'"))
  assert.ok(indexSource.includes("from './components/OverviewSystemTable.jsx'"))
  assert.ok(indexSource.includes("from './components/DetailHeader.jsx'"))
  assert.ok(indexSource.includes("from './components/ServiceHealthTable.jsx'"))
  assert.ok(indexSource.includes("from './components/OverviewSummary.jsx'"))
  assert.ok(indexSource.includes("from './components/MetricVisualTile.jsx'"))
  assert.ok(indexSource.includes("from './components/DetailTrendSection.jsx'"))
  assert.ok(indexSource.includes("from './components/HealthScoreHelp.jsx'"))
  assert.ok(indexSource.includes("from './components/OverviewInitialLoading.jsx'"))
  assert.ok(overviewSystemTableSource.includes("from './SystemHealthScoreTrendCell.jsx'"))

  assert.equal(indexSource.includes('const renderPendingIssues = () => ('), false)
  assert.equal(indexSource.includes('const renderPendingIssueAnalysis ='), false)
  assert.equal(indexSource.includes('const renderThresholdSettings ='), false)
  assert.equal(indexSource.includes('const Lamp ='), false)
  assert.equal(indexSource.includes('const HealthTable ='), false)
  assert.equal(indexSource.includes('const Legend ='), false)
  assert.equal(indexSource.includes('const DetailLoadingStatus ='), false)
  assert.equal(indexSource.includes('className="sho-system-table"'), false)
  assert.equal(indexSource.includes('className="sho-service-table"'), false)
  assert.equal(indexSource.includes('className="sho-detail-compact-header"'), false)
  assert.equal(indexSource.includes('const SummaryMetricCard ='), false)
  assert.equal(indexSource.includes('const SummaryTrendGroup ='), false)
  assert.equal(indexSource.includes('const StatusDistributionBar ='), false)
  assert.equal(indexSource.includes('const SystemHealthScoreTrendCell ='), false)
  assert.equal(indexSource.includes('const DetailHealthScoreTrendChart ='), false)
  assert.equal(indexSource.includes('const DetailServiceStatusTrendChart ='), false)
  assert.equal(indexSource.includes('const MetricVisualTile ='), false)
  assert.equal(indexSource.includes('const HealthScoreCalculationTooltip ='), false)
  assert.equal(indexSource.includes('const HealthScoreRangeHelpIcon ='), false)
  assert.equal(indexSource.includes('const HealthScoreColumnTitle ='), false)
  assert.equal(indexSource.includes('const OverviewInitialLoading ='), false)

  assert.ok(statusSource.includes('export const Lamp'))
  assert.ok(statusSource.includes('export const HealthRing'))
  assert.ok(statusSource.includes('export const HealthTable'))
  assert.ok(statusSource.includes('export const Legend'))
  assert.ok(pendingQueueSource.includes('export default function PendingIssueQueue'))
  assert.ok(thresholdSource.includes('export default function ThresholdSettingsContent'))
  assert.ok(detailLoadingSource.includes('export const DetailLoadingPanel'))
  assert.ok(overviewSystemTableSource.includes('export default function OverviewSystemTable'))
  assert.ok(detailHeaderSource.includes('export default function DetailHeader'))
  assert.ok(serviceHealthTableSource.includes('export default function ServiceHealthTable'))
  assert.ok(overviewSummarySource.includes('export default function OverviewSummary'))
  assert.ok(metricVisualTileSource.includes('export default function MetricVisualTile'))
  assert.ok(systemScoreTrendCellSource.includes('export default function SystemHealthScoreTrendCell'))
  assert.ok(detailTrendSectionSource.includes('export default function DetailTrendSection'))
  assert.ok(healthScoreHelpSource.includes('export const HealthScoreCalculationTooltip'))
  assert.ok(healthScoreHelpSource.includes('export const HealthScoreRangeHelpIcon'))
  assert.ok(healthScoreHelpSource.includes('export const HealthScoreColumnTitle'))
  assert.ok(overviewInitialLoadingSource.includes('export default function OverviewInitialLoading'))
})
